export default function usePageTitle() {
  const { pathname, search } = useLocation()
  const isFirstRender = useRef(true)

  useEffect(() => {
    const categoryId = new URLSearchParams(search).get('categoryId')
    const match =
      (pathname === '/parts' && categoryId && PARTS_CATEGORIES[categoryId]) ||
      ROUTES[pathname] ||
      ROUTES['/']

    document.title = match.full ? match.title : `${match.title}${SUFFIX}`

    const meta = document.querySelector('meta[name="description"]')
    if (meta && match.desc) meta.setAttribute('content', match.desc)

    // Яндекс.Метрика не видит переходы внутри SPA — отправляем просмотр вручную.
    // Первый рендер пропускаем: этот хит уже отправил init в index.html.
    if (isFirstRender.current) {
      isFirstRender.current = false
    } else if (typeof window.ym === 'function') {
      window.ym(111930393, 'hit', window.location.href, {
        title: document.title,
        referer: document.referrer,
      })
    }
  }, [pathname, search])
}
